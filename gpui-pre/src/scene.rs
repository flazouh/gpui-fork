/// What a [`Group`] does to its content when it is put on the scene.
///
/// The content is painted into a surface of its own, then this is applied to that surface as a whole and the result
/// is composited over what is under it. That is what a browser does for `opacity` below one: two shapes that overlap
/// in a group show as one surface, which giving each shape the opacity cannot do.
#[derive(Clone, Debug, PartialEq)]

pub struct GroupEffects {
    /// The group's opacity, from 0 to 1.
    pub opacity: f32,
    /// A colour matrix in the form of CSS `filter` and SVG's `feColorMatrix`, row by row: each row of five numbers
    /// gives red, green, blue and alpha as the sum of the five times red, green, blue, alpha and 1, on straight
    /// (not premultiplied) colours in 0 to 1. `None` leaves the colours as they are.
    pub colour_matrix: Option<[f32; 20]>,
    /// The standard deviation of a Gaussian blur applied first, in logical pixels as given to
    /// [`Window::paint_group`](crate::Window::paint_group) and in device pixels in a [`Group`] on the scene. Zero is
    /// no blur. The group's `bounds` must hold the blur's reach, about three times this on every side.
    pub blur: f32,
    /// A shadow of the group's alpha, under the group, as the CSS `drop-shadow()` filter function makes one. It
    /// is the last thing done to the group: the group's own colour matrix and blur are not in it.
    pub drop_shadow: Option<DropShadow>,
    /// A filter of what is behind the group, in a box, drawn before the group: the CSS `backdrop-filter`.
    pub backdrop: Option<BackdropEffects>,
}

/// A blur and a colour matrix applied to what the target holds under a box, which then takes its place.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct BackdropEffects {
    /// The standard deviation of the blur, in logical pixels in [`Window::paint_group`](crate::Window::paint_group)
    /// and in device pixels in a [`Group`].
    pub blur: f32,
    /// A colour matrix as in [`GroupEffects::colour_matrix`], applied after the blur.
    pub colour_matrix: Option<[f32; 20]>,
    /// The box: `[x, y, width, height]` in the units of `blur`.
    pub rect: [f32; 4],
    /// The radii of its corners: top left, top right, bottom right, bottom left, in the same units.
    pub radii: [f32; 4],
}

/// The shadow of a group's shape: its alpha, moved by `offset`, blurred by `blur`, in one colour.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DropShadow {
    /// How far the shadow is moved, in logical pixels as given to
    /// [`Window::paint_group`](crate::Window::paint_group) and in device pixels in a [`Group`] on the scene.
    pub offset: (f32, f32),
    /// The standard deviation of the blur, in the same units.
    pub blur: f32,
    /// The colour of the shadow, straight (not premultiplied) red, green, blue and alpha in 0 to 1.
    pub colour: [f32; 4],
}

impl Default for GroupEffects {
    fn default() -> Self {
        Self {
            opacity: 1.0,
            colour_matrix: None,
            blur: 0.0,
            drop_shadow: None,
            backdrop: None,
        }
    }
}

/// How a gradient continues outside its range.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GradientExtend {
    /// The end colours go on.
    Pad,
    /// The gradient starts again.
    Repeat,
    /// The gradient runs backwards and forwards.
    Reflect,
}

/// The shape of a gradient that GPUI's own two stop linear one is not: colours that run out from a point or round it.
#[derive(Clone, Copy, Debug, PartialEq)]
pub enum GradientShape {
    /// Colours along the line from `start` to `end`, in gradient space: offset 0 is at `start` and 1 at `end`.
    Linear {
        /// Where offset 0 is.
        start: (f32, f32),
        /// Where offset 1 is.
        end: (f32, f32),
    },
    /// Colours at distances from `centre`, in the gradient's own space: the stop at 0 is `start_radius` away and the
    /// one at 1 is `end_radius` away.
    Radial {
        /// The centre, in gradient space.
        centre: (f32, f32),
        /// Where offset 0 is.
        start_radius: f32,
        /// Where offset 1 is.
        end_radius: f32,
    },
    /// Colours at angles round `centre`: offset 0 is `start_angle` and 1 is `end_angle`, in radians, clockwise
    /// from the direction of +x when y points down.
    Sweep {
        /// The centre, in gradient space.
        centre: (f32, f32),
        /// Where offset 0 is.
        start_angle: f32,
        /// Where offset 1 is.
        end_angle: f32,
    },
}

/// A gradient with any number of stops (up to 16) of a shape GPUI's own gradient does not have. It is painted by the
/// renderer's own pass, with the stops' colours interpolated on premultiplied colours as CSS does.
#[derive(Clone, Debug, PartialEq)]
pub struct GradientFill {
    /// The shape.
    pub shape: GradientShape,
    /// How it goes on outside the range of its stops.
    pub extend: GradientExtend,
    /// The stops, in rising order of offset: where (0 to 1) and the straight red, green, blue and alpha.
    pub stops: Vec<(f32, [f32; 4])>,
    /// The affine map, `[a, b, c, d, e, f]` (`x' = a x + c y + e`, `y' = b x + d y + f`), from the window's
    /// coordinates (logical pixels in [`Window::paint_gradient_fill`](crate::Window::paint_gradient_fill), device
    /// pixels in a [`Group`]) to the gradient's space.
    pub inverse: [f32; 6],
}

/// Content that is painted apart and composited as one. The renderer paints `scene` into a surface the size of the
/// frame, applies `effects`, and draws the result over the area of `bounds`, cut to `content_mask`.
///
/// A platform that cannot do this flattens the group: its content is drawn in place with the opacity given to each
/// shape. That is [`Scene::flattened`].
#[derive(Clone)]
#[expect(missing_docs)]
pub struct Group {
    pub order: DrawOrder,
    pub bounds: Bounds<ScaledPixels>,
    pub content_mask: ContentMask<ScaledPixels>,
    pub effects: GroupEffects,
    pub scene: Arc<Scene>,
    /// What shows of the group is its alpha times the alpha of this scene (CSS `mask-image`), as the renderer
    /// paints it into a surface of its own. `None` is no mask.
    pub mask: Option<Arc<Scene>>,
    /// A group with a fill has no scene: the renderer paints this gradient over its bounds in the scene's place.
    pub fill: Option<Arc<GradientFill>>,
    /// The shape of the box of `effects.backdrop`, a scene that paints it opaque, when its corners are round.
    pub backdrop_shape: Option<Arc<Scene>>,
}

#[expect(missing_docs)]
impl Scene {
    pub fn clear(&mut self) {
        self.paint_operations.clear();
        self.primitive_bounds.clear();
        self.layer_stack.clear();
        self.paths.clear();
        self.shadows.clear();
        self.quads.clear();
        self.underlines.clear();
        self.monochrome_sprites.clear();
        self.subpixel_sprites.clear();
        self.polychrome_sprites.clear();
        self.surfaces.clear();
        self.groups.clear();
    }

    pub fn len(&self) -> usize {
        self.paint_operations.len()
    }

    pub fn push_layer(&mut self, bounds: Bounds<ScaledPixels>) {
        let order = self.primitive_bounds.insert(bounds);
        self.layer_stack.push(order);
        self.paint_operations
            .push(PaintOperation::StartLayer(bounds));
    }

    pub fn pop_layer(&mut self) {
        self.layer_stack.pop();
        self.paint_operations.push(PaintOperation::EndLayer);
    }

    pub fn insert_primitive(&mut self, primitive: impl Into<Primitive>) {
        let mut primitive = primitive.into();
        let clipped_bounds = primitive
            .bounds()
            .intersect(&primitive.content_mask().bounds);

        if clipped_bounds.is_empty() {
            return;
        }

        let order = self
            .layer_stack
            .last()
            .copied()
            .unwrap_or_else(|| self.primitive_bounds.insert(clipped_bounds));
        match &mut primitive {
            Primitive::Shadow(shadow) => {
                shadow.order = order;
                self.shadows.push(*shadow);
            }
            Primitive::Quad(quad) => {
                quad.order = order;
                self.quads.push(*quad);
            }
            Primitive::Path(path) => {
                path.order = order;
                path.id = PathId(self.paths.len());
                self.paths.push(path.clone());
            }
            Primitive::Underline(underline) => {
                underline.order = order;
                self.underlines.push(*underline);
            }
            Primitive::MonochromeSprite(sprite) => {
                sprite.order = order;
                self.monochrome_sprites.push(*sprite);
            }
            Primitive::SubpixelSprite(sprite) => {
                sprite.order = order;
                self.subpixel_sprites.push(*sprite);
            }
            Primitive::PolychromeSprite(sprite) => {
                sprite.order = order;
                self.polychrome_sprites.push(*sprite);
            }
            Primitive::Surface(surface) => {
                surface.order = order;
                self.surfaces.push(surface.clone());
            }
        }
        self.paint_operations
            .push(PaintOperation::Primitive(primitive));
    }

    /// Puts a group on the scene at the current layer. The group's own scene must be finished.
    pub fn insert_group(&mut self, mut group: Group) {
        let clipped_bounds = group.bounds.intersect(&group.content_mask.bounds);
        if clipped_bounds.is_empty() {
            return;
        }
        group.order = self
            .layer_stack
            .last()
            .copied()
            .unwrap_or_else(|| self.primitive_bounds.insert(clipped_bounds));
        self.groups.push(group.clone());
        self.paint_operations.push(PaintOperation::Group(group));
    }

    pub fn replay(&mut self, range: Range<usize>, prev_scene: &Scene) {
        for operation in &prev_scene.paint_operations[range] {
            match operation {
                PaintOperation::Group(group) => self.insert_group(group.clone()),
                PaintOperation::Primitive(primitive) => self.insert_primitive(primitive.clone()),
                PaintOperation::StartLayer(bounds) => self.push_layer(*bounds),
                PaintOperation::EndLayer => self.pop_layer(),
            }
        }
    }

    /// The scene with every group's content drawn in place, each shape with the group's opacity by itself. For a
    /// renderer that cannot composite a group. Two shapes of a group that overlap show through each other where a
    /// group would show one surface, and a colour matrix is left out. `None` when the scene has no group.
    pub fn flattened(&self) -> Option<Scene> {
        if self.groups.is_empty() {
            return None;
        }
        let mut flat = Scene::default();
        flat.replay_flat(self, 1.0);
        flat.finish();
        Some(flat)
    }

    fn replay_flat(&mut self, from: &Scene, opacity: f32) {
        for operation in &from.paint_operations {
            match operation {
                PaintOperation::Primitive(primitive) => {
                    self.insert_primitive(primitive.with_opacity(opacity));
                }
                PaintOperation::StartLayer(bounds) => self.push_layer(*bounds),
                PaintOperation::EndLayer => self.pop_layer(),
                PaintOperation::Group(group) => {
                    self.replay_flat(&group.scene, opacity * group.effects.opacity);
                }
            }
        }
    }

    pub fn finish(&mut self) {
        self.shadows.sort_by_key(|shadow| shadow.order);
        self.quads.sort_by_key(|quad| quad.order);
        self.paths.sort_by_key(|path| path.order);
        self.underlines.sort_by_key(|underline| underline.order);
        self.monochrome_sprites
            .sort_by_key(|sprite| (sprite.order, sprite.tile.tile_id));
        self.subpixel_sprites
            .sort_by_key(|sprite| (sprite.order, sprite.tile.tile_id));
        self.polychrome_sprites
            .sort_by_key(|sprite| (sprite.order, sprite.tile.tile_id));
        self.surfaces.sort_by_key(|surface| surface.order);
        self.groups.sort_by_key(|group| group.order);
    }

    #[cfg_attr(
        all(
            any(target_os = "linux", target_os = "freebsd"),
            not(any(feature = "x11", feature = "wayland"))
        ),
        allow(dead_code)
    )]
    pub fn batches(&self) -> impl Iterator<Item = PrimitiveBatch> + '_ {
        BatchIterator {
            shadows_start: 0,
            shadows_iter: self.shadows.iter().peekable(),
            quads_start: 0,
            quads_iter: self.quads.iter().peekable(),
            paths_start: 0,
            paths_iter: self.paths.iter().peekable(),
            underlines_start: 0,
            underlines_iter: self.underlines.iter().peekable(),
            monochrome_sprites_start: 0,
            monochrome_sprites_iter: self.monochrome_sprites.iter().peekable(),
            subpixel_sprites_start: 0,
            subpixel_sprites_iter: self.subpixel_sprites.iter().peekable(),
            polychrome_sprites_start: 0,
            polychrome_sprites_iter: self.polychrome_sprites.iter().peekable(),
            surfaces_start: 0,
            surfaces_iter: self.surfaces.iter().peekable(),
            groups_start: 0,
            groups_iter: self.groups.iter().peekable(),
        }
    }
}

